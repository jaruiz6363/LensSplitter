using System;
using System.Collections.Generic;
using System.Linq;

namespace AberrationCalculator.Core.Aberrations;

/// <summary>What one aberration is doing to the spot.</summary>
public sealed class AberrationContribution
{
    /// <summary>Coefficient name, e.g. "B", "F1", "B7".</summary>
    public string Name { get; init; } = "";

    /// <summary>Its raw transverse coefficient.</summary>
    public double Coefficient { get; init; }

    /// <summary>
    /// The RMS spot radius this aberration would produce if every other coefficient were
    /// zero - the re-normalised coefficient of Rosete-Aguilar and Rayces. Always positive,
    /// and directly comparable between aberrations: two aberrations with equal isolated
    /// values do equal damage on their own.
    /// </summary>
    public double Isolated { get; init; }

    /// <summary>
    /// This aberration's exact share of the mean square spot radius, with each cross term
    /// split evenly between the two aberrations that produce it. These sum to the total
    /// mean square exactly.
    ///
    /// <b>May be negative.</b> A negative share means this aberration is cancelling others:
    /// removing it would make the spot larger.
    /// </summary>
    public double Share { get; init; }

    /// <summary>
    /// <see cref="Share"/> as a percentage of the total mean square. Sums to 100% across
    /// all aberrations. Negative for an aberration that is balancing others, and above 100%
    /// for one that is being partly cancelled by them.
    /// </summary>
    public double Percent { get; init; }
}

/// <summary>What one surface is doing to the spot.</summary>
public sealed class SurfaceContribution
{
    /// <summary>Surface index, numbered as the source file numbers it.</summary>
    public int Surface { get; init; }

    /// <summary>
    /// Share of the mean square spot, cross terms with other surfaces split evenly.
    /// Sums to the total exactly. Negative means this surface is cancelling others - which
    /// is normal and often deliberate, since that is what a corrector element is for.
    /// </summary>
    public double Share { get; init; }

    /// <summary>Share as a percentage of the total. Sums to 100 across all surfaces.</summary>
    public double Percent { get; init; }

    /// <summary>
    /// How much of this surface's higher-order coefficient magnitude is INDUCED rather
    /// than generated by the surface itself. Near one means the surface is mostly reacting
    /// to aberration handed to it, and the fix is upstream rather than here.
    /// </summary>
    public double InducedFraction { get; init; }
}

/// <summary>
/// Attributes the predicted spot size to individual aberrations.
///
/// A table of coefficients does not answer the question a designer actually has, which is
/// "which one should I fix?" - the largest coefficient is often not the largest problem,
/// because the coefficients carry different units and enter the spot with different
/// weights. Re-normalising them fixes that. See M. Rosete-Aguilar and J. Rayces,
/// "Re-normalization of Buchdahl-Rimmer aberration coefficients to RMS expressions,"
/// <i>Proc. SPIE</i> <b>2730</b>, 499-502 (1996) - the geometric half of which is what
/// this implements - and the same authors' wave-aberration treatment in
/// <i>J. Mod. Opt.</i> <b>42</b>(12), 2435-2445 (1995).
///
/// Two different questions get two different numbers here, and conflating them is the trap:
///
/// <list type="bullet">
/// <item><b>Isolated</b> - what this aberration would do on its own. This is the paper's
/// re-normalised coefficient. It is what makes coefficients comparable with each other,
/// but the isolated values do NOT add up to the actual spot.</item>
/// <item><b>Share</b> - what this aberration contributes to the spot the design actually
/// has, including its interaction with everything else. These DO add up, exactly.</item>
/// </list>
///
/// The reason they differ is that the mean square spot is a quadratic form: it has cross
/// terms as well as squares, and a cross term can be negative. That is aberration
/// balancing, and it is the whole craft of lens design - a design where fifth-order
/// spherical is deliberately cancelling third-order will show a large isolated value for
/// each and a small, possibly negative, share.
/// </summary>
public static class ContributionAnalysis
{
    /// <summary>
    /// Decomposes the mean square spot radius at fractional field height
    /// <paramref name="h"/> into per-aberration contributions.
    ///
    /// Cross terms are split evenly between the pair that produces them, which is the
    /// standard way to make a quadratic form additive and is the only split that treats
    /// the two partners symmetrically. The shares then sum to the total exactly.
    /// </summary>
    public static IReadOnlyList<AberrationContribution> Compute(BuchdahlTerms totals, double h)
    {
        if (totals == null) throw new ArgumentNullException(nameof(totals));

        var share = new Dictionary<string, double>();
        var isolatedMs = new Dictionary<string, double>();

        foreach (var name in BuchdahlTerms.Names)
        {
            share[name] = 0.0;
            isolatedMs[name] = 0.0;
        }

        foreach (var (a, b, hPower, factor) in Prms.Terms)
        {
            double hp = hPower == 0 ? 1.0 : Math.Pow(h, hPower);
            double value = factor * totals[a] * totals[b] * hp;

            if (a == b)
            {
                share[a] += value;
                isolatedMs[a] += value;      // a diagonal term IS the isolated contribution
            }
            else
            {
                share[a] += 0.5 * value;
                share[b] += 0.5 * value;
            }
        }

        double total = Prms.MeanSquare(totals, h);

        return BuchdahlTerms.Names
            .Select(name => new AberrationContribution
            {
                Name = name,
                Coefficient = totals[name],
                Isolated = isolatedMs[name] > 0.0 ? Math.Sqrt(isolatedMs[name]) : 0.0,
                Share = share[name],
                Percent = Math.Abs(total) > 1e-30 ? 100.0 * share[name] / total : 0.0,
            })
            .ToList();
    }

    /// <summary>
    /// Attributes the mean square spot to individual SURFACES.
    ///
    /// Each surface contributes some amount to every total coefficient, and the spot is a
    /// quadratic form in those totals - so a surface interacts with every other surface just
    /// as one aberration interacts with another. Cross terms are split evenly again, and the
    /// shares sum to the total exactly.
    ///
    /// A negative share is a surface that is cancelling the others. That is normal and often
    /// deliberate: it is what a corrector element is for.
    /// </summary>
    public static IReadOnlyList<SurfaceContribution> BySurface(BuchdahlResult result, double h)
    {
        if (result == null) throw new ArgumentNullException(nameof(result));

        int count = result.PerSurface.Length;
        var totals = result.Totals;
        double totalMs = Prms.MeanSquare(totals, h);
        var rows = new List<SurfaceContribution>();

        for (int i = 0; i < count; i++)
        {
            var raw = result.PerSurface[i];
            if (raw == null) continue;

            // PerSurface is unscaled; the totals carry the F/number, so scale to match.
            var s = raw.Clone();
            foreach (var f in typeof(BuchdahlTerms).GetFields())
                if (f.FieldType == typeof(double))
                    f.SetValue(s, (double)f.GetValue(s)! * result.FNumber);

            double share = 0.0;
            foreach (var (a, b, hPower, factor) in Prms.Terms)
            {
                double hp = hPower == 0 ? 1.0 : Math.Pow(h, hPower);
                share += 0.5 * factor * hp * (s[a] * totals[b] + totals[a] * s[b]);
            }

            double own = 0.0, ind = 0.0;
            foreach (var name in new[] { "B5", "F1", "F2", "M1", "M2", "M3",
                                         "N1", "N2", "N3", "C5", "Pi5", "E5", "B7" })
            {
                ind += Math.Abs(result.Induced[i][name]);
                own += Math.Abs(result.Intrinsic[i][name])
                     + Math.Abs(result.Aspheric[i]?[name] ?? 0.0);
            }

            if (Math.Abs(share) < 1e-30 && own + ind < 1e-30) continue;

            rows.Add(new SurfaceContribution
            {
                Surface = i,
                Share = share,
                Percent = Math.Abs(totalMs) > 1e-30 ? 100.0 * share / totalMs : 0.0,
                InducedFraction = own + ind > 1e-30 ? ind / (own + ind) : 0.0,
            });
        }
        return rows;
    }

    /// <summary>
    /// True when the aberrations are materially cancelling one another, which is when the
    /// isolated values and the shares tell different stories and a reader needs warning.
    ///
    /// Measured by comparing the spot the design actually has against the spot it would
    /// have if every aberration acted independently. Well below one means heavy balancing.
    /// </summary>
    public static double BalancingRatio(BuchdahlTerms totals, double h)
    {
        double actual = Prms.MeanSquare(totals, h);
        double independent = 0.0;
        foreach (var c in Compute(totals, h)) independent += c.Isolated * c.Isolated;
        return independent > 1e-30 ? actual / independent : 1.0;
    }
}
