using System;
using System.Collections.Generic;
using AberrationCalculator.Core.Aberrations;

namespace AberrationCalculator.Core.Nat;

/// <summary>
/// The wave front coefficients of a centred system, per surface and in total, in the form nodal
/// aberration theory consumes.
///
/// <para>This is the end of the chain that runs: the computing scheme in Buchdahl's W
/// coordinates (<see cref="BuchdahlTableI"/> with <c>wCoordinates</c>), his VII Eqs. (6.5-6)
/// turning aberration coefficients into deformation coefficients, and his VII Eq. (3.4) turning
/// deformation into retardation - which is what a wave aberration is. The nine secondary
/// coefficients that come out ARE Thompson's <c>W060 W151 W240 W242 W331 W333 W420 W422
/// W511</c>; see <see cref="Deformation"/> for why the identification has no freedom in it.</para>
///
/// <para><b>Why per surface.</b> NAT displaces each surface's rotationally symmetric wave
/// aberration by that surface's own sigma vector and adds the results. It therefore needs the
/// contributions separately, not just their sum.</para>
///
/// <para><b>The split is exact.</b> Every step from the scheme's per-surface contributions to the
/// retardation coefficients is LINEAR: Eqs. (6.5-6) are linear in the aberration coefficients,
/// the <c>e</c> scaling of Sec. 7(a) is one factor per coefficient, and Eq. (3.4) adds a multiple
/// of a primary coefficient to a secondary one. So applying the chain surface by surface and
/// summing gives the same answer as applying it to the totals, to machine precision, and there is
/// no apportioning judgement anywhere in it. That is a property of the WAVE FRONT and not of the
/// transverse aberration: wave front deformation is additive over surfaces, which is exactly what
/// the induced terms of the transverse coefficients exist to repair.</para>
///
/// <para><b>What this does not settle, for fifth-order NAT.</b> The per-surface contributions
/// here are the scheme's own - intrinsic plus the induced part each surface generates from the
/// aberration already in the beam. Thompson's multinodal papers separate the two at fifth order
/// because the induced part is generated by the PERTURBED third order, so under a perturbation it
/// does not simply ride along on its surface's sigma. Nothing here decides that question; it
/// supplies the unperturbed per-surface coefficients, which are the input either way.</para>
/// </summary>
public static class WaveFront
{
    /// <summary>Per-surface and total wave front coefficients, with the geometry they used.</summary>
    public sealed class Result
    {
        /// <summary>
        /// Retardation coefficients contributed by each surface, indexed like the surfaces, so
        /// entry 0 is the object row and is zero. These are the ones NAT displaces by sigma.
        /// </summary>
        public Deformation[] PerSurface { get; init; } = Array.Empty<Deformation>();

        /// <summary>The sum of <see cref="PerSurface"/>: the system's wave front.</summary>
        public Deformation System { get; init; }

        /// <summary>
        /// Buchdahl's <c>e</c>, the axial distance from the paraxial exit pupil to the ideal
        /// image plane, in units of the focal length. Computed, not fitted - see
        /// <see cref="ExitPupilDistance"/>.
        /// </summary>
        public Scalar E { get; init; }

        /// <summary>The deformation coefficients, before Eq. (3.4). Kept because Buchdahl
        /// tabulates both and confusing them is a documented way to be quietly wrong.</summary>
        public Deformation SystemDeformation { get; init; }
    }

    /// <summary>
    /// Buchdahl's <c>e = (E'O0')</c>, Sec. 2: the axial distance from the paraxial exit pupil to
    /// the ideal image plane.
    ///
    /// <para>The p ray reaches the axis at the image and the q ray reaches it at the exit pupil,
    /// so the separation follows from the two ray heights and their image-space angles:</para>
    /// <code>
    ///     e = (y_p v_q' - y_q v_p') / (v_p' v_q')
    /// </code>
    /// <para>evaluated at the last surface, heights being continuous across a refraction. On
    /// Buchdahl's own triplet this gives 0.968799 against the 0.968801 implied by his Table I,
    /// which is what lets that table be used as a check with nothing fitted.</para>
    /// </summary>
    public static Scalar ExitPupilDistance(BuchdahlTableIRow last)
    {
        Scalar yp = last.T[1], yq = last.T[4], vp = last.VpPrime, vq = last.VqPrime;
        Scalar denom = vp * vq;
        if (SMath.Abs(denom) < 1e-300) return 0.0;
        return (yp * vq - yq * vp) / denom;
    }

    /// <summary>
    /// The wave front coefficients of a system, running the scheme in W coordinates.
    ///
    /// <para>The setup mirrors <see cref="TertiaryCoefficients"/>: the same stop parameter, the
    /// same <c>iota</c> for a finite conjugate, and the same aspheric increments, because a
    /// coefficient computed under a different convention is not comparable with one that is not.
    /// Returns null when the system has no usable stop.</para>
    /// </summary>
    public static Result? FromSystem(Models.OpticalSystem system, Scalar[] indices,
                                     RayTrace.ParaxialResult paraxial)
    {
        if (system == null) throw new ArgumentNullException(nameof(system));
        if (indices == null) throw new ArgumentNullException(nameof(indices));
        if (paraxial == null) throw new ArgumentNullException(nameof(paraxial));

        int stop = system.StopSurfaceIndex;
        int last = system.LastOpticalSurface();
        if (stop < 0 || stop >= system.Surfaces.Count || last < 1) return null;

        // Signed after each reflection, as TertiaryCoefficients.Attach signs them. Handed the
        // plain indices the scheme saw a mirror as a curved surface with no index step, and
        // every coefficient of a reflecting system came back exactly zero - silently, on the
        // telescope and the parabola alike. The same array comes back when nothing reflects.
        indices = TertiaryCoefficients.SignedIndices(system, indices);

        Scalar t0 = system.Surfaces[0].Thickness;
        Scalar iota = Scalar.IsInfinity(t0) ? 0.0 : -paraxial.Efl / t0;

        var scheme = BuchdahlScheme.Compute(system.Surfaces, indices, paraxial.Efl,
                                            system.Surfaces[stop].SemiDiameter, iota);

        Scalar stopParameter = Scalar.IsInfinity(t0)
            ? scheme.P
            : paraxial.EntrancePupilPosition / paraxial.Efl;

        // The aspheric increments are differenced against an all-spherical run, exactly as the
        // tertiary route does it; Build returns null when nothing is figured.
        var sphericalW = BuchdahlTableI.Compute(system.Surfaces, indices, paraxial.Efl,
                                                stopParameter, iota: iota, wCoordinates: true);
        var macro = BuchdahlCoefficients.Compute(system, paraxial);
        var increments = AsphericSchemeIncrements.Build(macro, sphericalW, last);

        var rows = increments == null
            ? sphericalW
            : BuchdahlTableI.Compute(system.Surfaces, indices, paraxial.Efl, stopParameter,
                                     increments, iota: iota, wCoordinates: true);

        return FromScheme(rows, last);
    }

    /// <summary>
    /// The wave front coefficients from a scheme that was run in W coordinates.
    /// </summary>
    /// <param name="rows">
    /// A computed scheme. It MUST have been produced with <c>wCoordinates: true</c>; VII
    /// Eq. (6.6) is stated for W coordinates and the fifth-order coefficients differ between the
    /// two systems by up to six per cent (VI Table II), which is too small to notice as an error.
    /// </param>
    /// <param name="lastSurface">Index of the last optical surface.</param>
    public static Result FromScheme(IReadOnlyList<BuchdahlTableIRow> rows, int lastSurface)
    {
        if (rows == null) throw new ArgumentNullException(nameof(rows));
        if (lastSurface < 1 || lastSurface >= rows.Count)
            throw new ArgumentOutOfRangeException(nameof(lastSurface));

        Scalar e = ExitPupilDistance(rows[lastSurface]);
        if (SMath.Abs(e) < 1e-300) e = 1.0;

        // Sec. 7(a): with e as the unit of length each aberration coefficient takes a power of e,
        // the barred ones taking one more, and the deformation coefficients are restored
        // afterwards by e^-3 at primary order and e^-5 at secondary.
        Scalar e2 = e * e, e3 = e2 * e, e4 = e3 * e;
        Scalar p3 = 1.0 / e3, p5 = 1.0 / (e4 * e);

        var perSurface = new Deformation[rows.Count];
        Scalar[] acc = new Scalar[14];

        for (int j = 1; j <= lastSurface; j++)
        {
            var t = rows[j].T;
            var scaled = Deformation.FromWCoordinates(
                t[10] / e, t[11], t[12] * e, t[13] * e, t[14] * e2,
                t[41] / e, t[42], t[52] * e, t[56] * e, t[57] * e2,
                t[62] * e2, t[63] * e3, t[67] * e3, t[68] * e4);

            var d = new Deformation(
                scaled.Pi1 * p3, scaled.Pi2 * p3, scaled.Pi3 * p3, scaled.Pi4 * p3, scaled.Pi5 * p3,
                scaled.Sigma1 * p5, scaled.Sigma2 * p5, scaled.Sigma3 * p5, scaled.Sigma4 * p5,
                scaled.Sigma5 * p5, scaled.Sigma6 * p5, scaled.Sigma7 * p5, scaled.Sigma8 * p5,
                scaled.Sigma9 * p5);

            // Eq. (3.4) is linear and e is a system constant, so converting deformation to
            // retardation surface by surface and summing is the same as converting the sum.
            perSurface[j] = d.ToRetardation(e);

            acc[0] += d.Pi1; acc[1] += d.Pi2; acc[2] += d.Pi3; acc[3] += d.Pi4; acc[4] += d.Pi5;
            acc[5] += d.Sigma1; acc[6] += d.Sigma2; acc[7] += d.Sigma3; acc[8] += d.Sigma4;
            acc[9] += d.Sigma5; acc[10] += d.Sigma6; acc[11] += d.Sigma7; acc[12] += d.Sigma8;
            acc[13] += d.Sigma9;
        }

        var systemD = new Deformation(acc[0], acc[1], acc[2], acc[3], acc[4], acc[5], acc[6],
                                      acc[7], acc[8], acc[9], acc[10], acc[11], acc[12], acc[13]);

        return new Result
        {
            PerSurface = perSurface,
            System = systemD.ToRetardation(e),
            SystemDeformation = systemD,
            E = e,
        };
    }
}
